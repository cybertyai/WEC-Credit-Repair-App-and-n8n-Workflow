-- ---------------------------------------------------------------
-- Credit score snapshots pulled per bureau over time
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS score_history (
  history_id    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  case_id       TEXT NOT NULL REFERENCES cases(case_id),
  bureau        TEXT NOT NULL CHECK (bureau IN ('experian','transunion','equifax')),
  score         INTEGER NOT NULL CHECK (score BETWEEN 300 AND 850),
  score_model   TEXT NOT NULL DEFAULT 'FICO 8',
  pulled_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_score_history_case_bureau
  ON score_history (case_id, bureau, pulled_at DESC);

COMMENT ON TABLE score_history IS
  'One row per credit bureau score pull. Used for score tracking charts in the client portal.';

-- ---------------------------------------------------------------
-- FDCPA / FCRA legal demand letters generated by or for clients
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS legal_letter_requests (
  request_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  case_id         TEXT REFERENCES cases(case_id),
  letter_type     TEXT NOT NULL,   -- e.g. 'fdcpa_debt_validation', 'fcra_method_of_verification'
  power_rating    TEXT NOT NULL DEFAULT 'medium'
                    CHECK (power_rating IN ('medium','strong','nuclear')),
  recipient_name  TEXT,
  recipient_addr  TEXT,
  violation_desc  TEXT,
  letter_body     TEXT NOT NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_legal_letters_case
  ON legal_letter_requests (case_id, created_at DESC);

COMMENT ON TABLE legal_letter_requests IS
  'FDCPA / FCRA demand letters generated in the Legal Letters tool. Not CROA-regulated since client generates these directly.';

-- ---------------------------------------------------------------
-- Webhook event log — incoming n8n webhook calls for debugging
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS webhook_log (
  log_id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  workflow    TEXT,
  payload     JSONB,
  result      JSONB,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------
-- Performance indexes on existing tables
-- ---------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_cases_email        ON cases (email);
CREATE INDEX IF NOT EXISTS idx_cases_status       ON cases (case_status);
CREATE INDEX IF NOT EXISTS idx_letters_case_round ON dispute_letters (case_id, round, letter_status);
CREATE INDEX IF NOT EXISTS idx_neg_items_case     ON negative_items (case_id, analysis_status);
CREATE INDEX IF NOT EXISTS idx_notifications_case ON notifications (case_id, sent_at DESC);

-- ---------------------------------------------------------------
-- RLS for new tables
-- ---------------------------------------------------------------
ALTER TABLE score_history          ENABLE ROW LEVEL SECURITY;
ALTER TABLE legal_letter_requests  ENABLE ROW LEVEL SECURITY;

CREATE POLICY "clients_read_own_scores"
  ON score_history FOR SELECT
  USING (case_id IN (
    SELECT case_id FROM cases WHERE email = auth.jwt() ->> 'email'
  ));

CREATE POLICY "clients_manage_own_legal_letters"
  ON legal_letter_requests FOR ALL
  USING (case_id IN (
    SELECT case_id FROM cases WHERE email = auth.jwt() ->> 'email'
  ));
